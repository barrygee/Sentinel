/**
 * Escape a string for safe interpolation into HTML built by hand — the
 * screen-reader data tables the map controls render outside the Vue tree.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
