CALLER_ACCESS: dict[str, CallerAccess] = {**SERVICE_ACCESS, **DECODER_ACCESS}

VERIFYING_SERVICES: tuple[str, ...] = (CORE_USER, "radio", "sdr-manager-local")
"""The processes that serve internal routes, so get the list of accepted callers."""

assert set(SERVICE_ACCESS) == set(SERVICE_PERMISSIONS), "every NATS user needs an HTTP entry, and back"


def _access(caller: str) -> CallerAccess | None:
    return CALLER_ACCESS.get(caller)


def may_register(caller: str, service_id: str) -> bool:
    """True when `caller` may register `service_id` in core's registry."""
    access = _access(caller)
    return caller == CORE_USER or (access is not None and access.registers_as == service_id)


def registration_refusal(caller: str, kind: str, routes: list[str]) -> str | None:
    """Why `caller` may not register a manifest of `kind` claiming `routes`, or None when it may.

    Checked after `may_register` (the id is the caller's own). A service claims
    exactly its own kind and route prefixes: another kind would let it pose as
    the docs or SDR Manager, and another prefix would let it take that route
    whenever its owner isn't registered (the registry only refuses a route a
    *live* registration holds). Core is let through, as everywhere.
    """
    if caller == CORE_USER:
        return None
    access = _access(caller)
    if access is None or access.registers_as is None:
        return "this credential registers no service"
    if kind != access.registers_kind:
        return f"{caller} registers as kind {access.registers_kind!r}, not {kind!r}"
    foreign = sorted(set(routes) - access.route_prefixes)
    if foreign:
        return f"{caller} may not claim the route(s) {', '.join(foreign)}"
    return None


def may_use_secret(caller: str, namespace: str, key: str) -> bool:
    """True when `caller` may read or write the secret setting (namespace, key)."""
    access = _access(caller)
    return caller == CORE_USER or (access is not None and (namespace, key) in access.secret_settings)


def may_fetch_iq_captures(caller: str) -> bool:
    """True when `caller` may fetch or discard the hub's staged IQ captures."""
    access = _access(caller)
    return caller == CORE_USER or (access is not None and access.fetches_iq_captures)


def may_list_services(caller: str, kind: str) -> bool:
    """True when `caller` may list core's registered services of manifest `kind`."""
    access = _access(caller)
    return caller == CORE_USER or (access is not None and kind in access.lists_service_kinds)


def may_manage_local_sdrs(caller: str) -> bool:
    """True when `caller` may manage this machine's SDRs with its service bearer.

    Core is deliberately not let through: only sdr-manager-remote manages
    SDR hosts, and every other manager signs in with the console password.
    """
    access = _access(caller)
    return access is not None and access.manages_local_sdrs


def may_decode(caller: str, kind: str) -> bool:
    """True when `caller` may act as a decoder of `kind`.

    Core is deliberately not let through: no in-process code posts decoder
    events over HTTP, so a decoder endpoint only ever has a decoder calling.
    """
    access = _access(caller)
    return access is not None and access.decoder_kind == kind
