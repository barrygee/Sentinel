"""What each Sentinel caller may do on the deployment's internal HTTP surfaces (plan §4.5, P7.4b).

Every service and every decoder holds its own HTTP credential, generated by the
one-shot `service-credentials` compose service
(`backend/scripts/generate_service_credentials.py`). The processes that serve
internal routes (core and the radio hub) know each credential only by its
SHA-256 hash and which caller it belongs to, and this table says what that
caller is allowed to do:

  - register itself with core's service registry, under its own id only
  - read or write a secret setting, only the ones it owns
  - fetch the hub's staged IQ captures (the SDR section collects them)
  - act as a decoder of one kind: read its config, post its events, register
    its manifest

A caller the table doesn't mention gets nothing. Like the NATS table
(`nats_permissions.py`), a new service or decoder kind must be added here, and
`docker compose up` regenerates the credentials and the hash lists.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from backend.platform.nats_permissions import CORE_USER, SERVICE_PERMISSIONS


@dataclass(frozen=True)
class CallerAccess:
    """One caller's allowed internal actions."""

    registers_as: str | None = None
    """The service id it may register in core's registry (its own)."""
    secret_settings: frozenset[tuple[str, str]] = field(default_factory=frozenset)
    """The (namespace, key) secret settings it may read and write."""
    fetches_iq_captures: bool = False
    decoder_kind: str | None = None
    """The decoder kind it may act as (ingest, config, manifest registration)."""


SERVICE_ACCESS: dict[str, CallerAccess] = {
    # Core is the trusted centre (and the test suite's in-process app, which
    # hosts every section, runs as core): whatever a section may do, core may
    # too; `may_*` below lets it through every check.
    CORE_USER: CallerAccess(),
    "radio": CallerAccess(registers_as="radio"),
    "space": CallerAccess(registers_as="space"),
    "land": CallerAccess(registers_as="land"),
    "air": CallerAccess(registers_as="air"),
    # The AISStream key is Sea's: it holds the one connection the key allows.
    "sea": CallerAccess(registers_as="sea", secret_settings=frozenset({("sea", "aisstreamApiKey")})),
    "sdr": CallerAccess(registers_as="sdr", fetches_iq_captures=True),
}
"""Services, keyed by the same name as their NATS user (`core` for the app)."""

DECODER_ACCESS: dict[str, CallerAccess] = {
    "voice-decoder": CallerAccess(decoder_kind="voice"),
    "aprs-decoder": CallerAccess(decoder_kind="aprs"),
    "ais-decoder": CallerAccess(decoder_kind="ais"),
    "stub-decoder": CallerAccess(decoder_kind="stub"),
}
"""Decoder sidecars, keyed by their compose service name."""

CALLER_ACCESS: dict[str, CallerAccess] = {**SERVICE_ACCESS, **DECODER_ACCESS}

VERIFYING_SERVICES: tuple[str, ...] = (CORE_USER, "radio")
"""The processes that serve internal routes, so get the list of accepted callers."""

assert set(SERVICE_ACCESS) == set(SERVICE_PERMISSIONS), "every NATS user needs an HTTP entry, and back"


def _access(caller: str) -> CallerAccess | None:
    return CALLER_ACCESS.get(caller)


def may_register(caller: str, service_id: str) -> bool:
    """True when `caller` may register `service_id` in core's registry."""
    access = _access(caller)
    return caller == CORE_USER or (access is not None and access.registers_as == service_id)


def may_use_secret(caller: str, namespace: str, key: str) -> bool:
    """True when `caller` may read or write the secret setting (namespace, key)."""
    access = _access(caller)
    return caller == CORE_USER or (access is not None and (namespace, key) in access.secret_settings)


def may_fetch_iq_captures(caller: str) -> bool:
    """True when `caller` may fetch or discard the hub's staged IQ captures."""
    access = _access(caller)
    return caller == CORE_USER or (access is not None and access.fetches_iq_captures)


def may_decode(caller: str, kind: str) -> bool:
    """True when `caller` may act as a decoder of `kind`.

    Core is deliberately not let through: no in-process code posts decoder
    events over HTTP, so a decoder endpoint only ever has a decoder calling.
    """
    access = _access(caller)
    return access is not None and access.decoder_kind == kind
